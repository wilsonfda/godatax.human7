# -*- coding: utf-8 -*-
"""
GDX_SKILL_RECORD_NEW_STUDY - stage 1: read an intake JSON produced by
GDX_SKILL_NEW_STUDY and generate the Firebird 2.5 load scripts for it.

Unlike GDX_SKILL_LOAD_RLT_MODEL_DB's 01-08 scripts (which use fixed, hand-picked
surrogate keys because they load one frozen historical dataset), the scripts
generated here NEVER hardcode a GDX_PSY_*.ID_* value. Every INSERT either
leaves the id column out (the schema's BEFORE INSERT triggers assign it from
the matching SEQ_GDX_PSY_* sequence) or is wrapped in a Firebird 2.5
`EXECUTE BLOCK` that captures the generated id with `RETURNING ... INTO
:variable` and reuses that variable for the child rows in the same block.
This is required so the same generator can be re-run safely against a live
database that already has other studies/instruments in it, without needing
to know in advance what the next free id is.

GDX_PSY_PHENOMENON and GDX_PSY_CONSTRUCT rows (and the study row itself) are
looked up by name/title first and only inserted if missing, because
GDX_SKILL_NEW_STUDY's interview explicitly asks the user to reuse an existing
phenomenon/construct name when one already covers the new instrument (see its
SKILL.md step 1.3/1.4). GDX_PSY_INSTRUMENT/VARIABLE/INDICATOR/ITEM rows are
always inserted (no reuse-by-name) -- those ARE the new thing being onboarded.

Usage:
    python generate_new_study_scripts.py <path/to/intake.json> [--out-dir <dir>]

Default --out-dir is the same folder the intake.json lives in (normally
GDX_HUMAN/0_new_instrument/new_study_intake/<slug>/).

Writes:
    01_new_study.sql
    02_new_instrument_01_<instrument-slug>.sql   (one per instrument, numbered)
"""
import argparse
import importlib.util
import json
import os
import re
import sys


def load_validator():
    """Import validate_intake.py from the sibling GDX_SKILL_NEW_STUDY skill
    folder instead of duplicating its checks here."""
    here = os.path.dirname(os.path.abspath(__file__))
    candidate = os.path.normpath(os.path.join(
        here, "..", "..", "GDX_SKILL_NEW_STUDY", "scripts", "validate_intake.py"))
    if not os.path.isfile(candidate):
        return None
    spec = importlib.util.spec_from_file_location("validate_intake", candidate)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def slugify(text):
    text = re.sub(r"[^a-zA-Z0-9]+", "_", text.strip().lower())
    return re.sub(r"_+", "_", text).strip("_")[:60] or "instrument"


def sql_str(value):
    if value is None:
        return "NULL"
    return "'" + str(value).replace("'", "''") + "'"


def sql_num(value):
    if value is None:
        return "NULL"
    return str(value)


def sql_int01(value, default=0):
    v = default if value is None else value
    return "1" if v in (1, True, "1") else "0"


HEADER = """/* ============================================================================
   {title}
   Generated by GDX_SKILL_RECORD_NEW_STUDY from {source}.
   Prerequisite: psychometrics_model_firebird25.sql already applied.
   Safe to re-run: GDX_PSY_STUDY/GDX_PSY_PHENOMENON/GDX_PSY_CONSTRUCT rows are
   reused by name/title if they already exist; GDX_PSY_INSTRUMENT and
   everything under it are always inserted fresh (this is the new thing being
   registered) and will fail loudly on a genuine duplicate (NAME, VERSION)
   instead of silently reusing it.
   ============================================================================ */

"""


def gen_study_script(study, source_name):
    title = study["title"]
    objective = study.get("objective")
    method = study.get("method")
    start_date = study.get("start_date")
    end_date = study.get("end_date")
    status = study.get("status", "PLANNED")

    body = f"""EXECUTE BLOCK AS
DECLARE VARIABLE V_ID_STUDY BIGINT;
BEGIN
  SELECT ID_STUDY FROM GDX_PSY_STUDY WHERE TITLE = {sql_str(title)} INTO :V_ID_STUDY;
  IF (:V_ID_STUDY IS NULL) THEN
  BEGIN
    INSERT INTO GDX_PSY_STUDY (TITLE, OBJECTIVE, METHOD, START_DATE, END_DATE, STATUS)
      VALUES ({sql_str(title)}, {sql_str(objective)}, {sql_str(method)}, {sql_str(start_date)}, {sql_str(end_date)}, {sql_str(status)})
      RETURNING ID_STUDY INTO :V_ID_STUDY;
  END
END
"""
    return HEADER.format(title="Data load - GDX_PSY_STUDY", source=source_name) + body


def gen_instrument_script(instrument, source_name):
    lines = []
    decl = ["DECLARE VARIABLE V_ID_PHENOMENON BIGINT;", "DECLARE VARIABLE V_ID_INSTRUMENT BIGINT;",
            "DECLARE VARIABLE V_ID_ITEM BIGINT;"]

    constructs = instrument["constructs"]
    construct_var = {}  # name -> sql variable name
    for i, c in enumerate(constructs, start=1):
        var = f"V_ID_CONSTRUCT_{i}"
        construct_var[c["name"]] = var
        decl.append(f"DECLARE VARIABLE {var} BIGINT;")

    variables = instrument["variables"]
    variable_indicator_var = {}  # variable name -> (var_id_variable, var_id_indicator)
    for i, v in enumerate(variables, start=1):
        vvar = f"V_ID_VARIABLE_{i}"
        ivar = f"V_ID_INDICATOR_{i}"
        variable_indicator_var[v["name"]] = (vvar, ivar)
        decl.append(f"DECLARE VARIABLE {vvar} BIGINT;")
        decl.append(f"DECLARE VARIABLE {ivar} BIGINT;")

    anchor_sets = {a["key"]: a["alternatives"] for a in instrument.get("response_anchor_sets", [])}

    body = ["BEGIN"]

    body.append(f"  SELECT ID_PHENOMENON FROM GDX_PSY_PHENOMENON WHERE NAME = {sql_str(instrument['phenomenon_name'])} INTO :V_ID_PHENOMENON;")
    body.append("  IF (:V_ID_PHENOMENON IS NULL) THEN")
    body.append("  BEGIN")
    body.append(f"    INSERT INTO GDX_PSY_PHENOMENON (NAME, DESCRIPTION) VALUES ({sql_str(instrument['phenomenon_name'])}, {sql_str(instrument.get('phenomenon_description'))})")
    body.append("      RETURNING ID_PHENOMENON INTO :V_ID_PHENOMENON;")
    body.append("  END")
    body.append("")

    for c in constructs:
        var = construct_var[c["name"]]
        body.append(f"  SELECT ID_CONSTRUCT FROM GDX_PSY_CONSTRUCT WHERE NAME = {sql_str(c['name'])} INTO :{var};")
        body.append(f"  IF (:{var} IS NULL) THEN")
        body.append("  BEGIN")
        body.append(f"    INSERT INTO GDX_PSY_CONSTRUCT (NAME, DOMAIN, DEFINITION) VALUES ({sql_str(c['name'])}, {sql_str(c.get('domain', 'PSYCHOMETRIC_NEW'))}, {sql_str(c['definition'])})")
        body.append(f"      RETURNING ID_CONSTRUCT INTO :{var};")
        body.append("  END")
        body.append(f"  INSERT INTO GDX_PSY_PHENOMENON_CONSTRUCT (ID_PHENOMENON, ID_CONSTRUCT, RELATION_TYPE)")
        body.append(f"    SELECT :V_ID_PHENOMENON, :{var}, 'OPERATIONALIZES'")
        body.append(f"    FROM RDB$DATABASE")
        body.append(f"    WHERE NOT EXISTS (SELECT 1 FROM GDX_PSY_PHENOMENON_CONSTRUCT WHERE ID_PHENOMENON = :V_ID_PHENOMENON AND ID_CONSTRUCT = :{var});")
        body.append("")

    body.append(f"  INSERT INTO GDX_PSY_INSTRUMENT (NAME, VERSION, TYPE, DESCRIPTION, INSTRUCTIONS, ACTIVE)")
    body.append(f"    VALUES ({sql_str(instrument['name'])}, {sql_str(instrument.get('version'))}, {sql_str(instrument['type'])}, {sql_str(instrument.get('description'))}, {sql_str(instrument.get('instructions'))}, 1)")
    body.append(f"    RETURNING ID_INSTRUMENT INTO :V_ID_INSTRUMENT;")
    body.append("")

    for c in constructs:
        var = construct_var[c["name"]]
        weight = sql_num(c.get("weight_in_instrument", 1))
        body.append(f"  INSERT INTO GDX_PSY_INSTRUMENT_CONSTRUCT (ID_INSTRUMENT, ID_CONSTRUCT, WEIGHT) VALUES (:V_ID_INSTRUMENT, :{var}, {weight});")
    body.append("")

    for v in variables:
        vvar, ivar = variable_indicator_var[v["name"]]
        cvar = construct_var[v["construct_name"]]
        body.append(f"  INSERT INTO GDX_PSY_VARIABLE (ID_CONSTRUCT, NAME, DESCRIPTION, OPERATIONAL_DEFINITION, VARIABLE_TYPE, MEASUREMENT_LEVEL)")
        body.append(f"    VALUES (:{cvar}, {sql_str(v['name'])}, {sql_str(v.get('description'))}, {sql_str(v.get('operational_definition'))}, {sql_str(v.get('variable_type', 'PSYCHOLOGICAL'))}, {sql_str(v.get('measurement_level'))})")
        body.append(f"    RETURNING ID_VARIABLE INTO :{vvar};")
        body.append(f"  INSERT INTO GDX_PSY_INDICATOR (ID_VARIABLE, NAME, DESCRIPTION, INDICATOR_TYPE, MEASUREMENT_UNIT, DIRECTION, MIN_VALUE, MAX_VALUE)")
        body.append(f"    VALUES (:{vvar}, {sql_str(v['indicator_name'])}, {sql_str(v.get('indicator_description'))}, {sql_str(v.get('indicator_type'))}, {sql_str(v.get('measurement_unit'))}, {sql_str(v.get('direction'))}, {sql_num(v.get('min_value'))}, {sql_num(v.get('max_value'))})")
        body.append(f"    RETURNING ID_INDICATOR INTO :{ivar};")
        body.append("")

    for item in instrument["items"]:
        order = item["order"]
        body.append(f"  INSERT INTO GDX_PSY_INSTRUMENT_ITEM (ID_INSTRUMENT, ITEM_ORDER, STATEMENT_TEXT, RESPONSE_TYPE, REQUIRED, WEIGHT)")
        body.append(f"    VALUES (:V_ID_INSTRUMENT, {order}, {sql_str(item['statement_text'])}, {sql_str(item['response_type'])}, {sql_int01(item.get('required'), default=1)}, {sql_num(item.get('weight', 1))})")
        body.append(f"    RETURNING ID_ITEM INTO :V_ID_ITEM;")

        anchor_key = item.get("anchor_set")
        if anchor_key:
            for alt in anchor_sets.get(anchor_key, []):
                body.append(f"  INSERT INTO GDX_PSY_ITEM_ALTERNATIVE (ID_ITEM, ALTERNATIVE_ORDER, LABEL, NUMERIC_VALUE) VALUES (:V_ID_ITEM, {alt['order']}, {sql_str(alt['label'])}, {sql_num(alt['numeric_value'])});")

        targets = [{"variable_name": item["variable_name"],
                    "reversed": item.get("reversed", 0),
                    "indicator_item_weight": item.get("indicator_item_weight", item.get("weight", 1))}]
        targets += item.get("extra_variables", [])
        for t in targets:
            _, ivar = variable_indicator_var[t["variable_name"]]
            body.append(f"  INSERT INTO GDX_PSY_INDICATOR_ITEM (ID_INDICATOR, ID_ITEM, WEIGHT, REVERSED) VALUES (:{ivar}, :V_ID_ITEM, {sql_num(t.get('indicator_item_weight', 1))}, {sql_int01(t.get('reversed'), default=0)});")
        body.append(f"  -- item order: {order}")
        body.append("")

    body.append("END")

    full = "EXECUTE BLOCK AS\n" + "\n".join(decl) + "\nBEGIN\n" + "\n".join(body[1:])
    header = HEADER.format(title=f"Data load - GDX_PSY_INSTRUMENT '{instrument['name']}' and everything under it",
                            source=source_name)
    return header + full + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("intake_json")
    ap.add_argument("--out-dir", default=None)
    args = ap.parse_args()

    validator = load_validator()
    with open(args.intake_json, "r", encoding="utf-8") as f:
        data = json.load(f)

    if validator is not None:
        problems = validator.validate(data)
        if problems.items:
            print(f"REFUSING TO GENERATE: {len(problems.items)} problem(s) in {args.intake_json}:", file=sys.stderr)
            for msg in problems.items:
                print(f"  - {msg}", file=sys.stderr)
            sys.exit(1)
    else:
        print("WARNING: could not find validate_intake.py in ../../GDX_SKILL_NEW_STUDY/scripts/ "
              "-- proceeding WITHOUT validation. Run that script manually first.", file=sys.stderr)

    out_dir = args.out_dir or os.path.dirname(os.path.abspath(args.intake_json))
    os.makedirs(out_dir, exist_ok=True)
    source_name = os.path.basename(args.intake_json)

    study_path = os.path.join(out_dir, "01_new_study.sql")
    with open(study_path, "w", encoding="utf-8") as f:
        f.write(gen_study_script(data["study"], source_name))
    print(f"wrote {study_path}")

    for i, instrument in enumerate(data["instruments"], start=1):
        slug = slugify(instrument["name"])
        path = os.path.join(out_dir, f"02_new_instrument_{i:02d}_{slug}.sql")
        with open(path, "w", encoding="utf-8") as f:
            f.write(gen_instrument_script(instrument, source_name))
        n_items = len(instrument["items"])
        n_vars = len(instrument["variables"])
        print(f"wrote {path}  ({n_vars} variable(s), {n_items} item(s))")

    print("\nDone. Review the generated .sql, then run execute_new_study.js "
          "(see this skill's SKILL.md) -- start with --dry-run.")


if __name__ == "__main__":
    main()
