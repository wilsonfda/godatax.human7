/*
 GoDataX - Coerencia Cardiaca, VFC e Movesense MD - Firebird 2.5

 TABELAS
 PARTICIPANT: pessoa pseudonimizada.
 DEVICE: equipamento e firmware.
 SESSION: configuracao da captura.
 RR_INTERVAL: RR e BPM por batimento.
 ECG_SAMPLE: sinal ECG bruto por amostra.
 MOTION: movimento, campo magnetico e temperatura por amostra.
 HRV_WINDOW: RMSSD, SDNN e coerencia por janela.
 DEVICE_EVENT: bateria, contato, Bluetooth, reset e erros.

 Movesense MD: ECG 125/128/200/250/256/500/512 Hz; 15 bits;
 HR 20-240 BPM; RR 250-3000 ms; movimento 12.5/26/52/104/208 Hz.
 RR tem resolucao de 1 ms com ECG a 125 Hz e 8 ms nas demais taxas.
*/

CREATE TABLE GDX_CC_PERSON (
 ID_PERSON BIGINT NOT NULL,
 EXTERNAL_CODE VARCHAR(80),
 CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 ACTIVE_FLAG SMALLINT DEFAULT 1 NOT NULL,
 CONSTRAINT PK_GDX_CC_PERSON PRIMARY KEY (ID_PERSON),
 CONSTRAINT UQ_GDX_CC_PART_EXT UNIQUE (EXTERNAL_CODE),
 CONSTRAINT CK_GDX_CC_PART_ACTIVE CHECK (ACTIVE_FLAG IN (0,1))
);

CREATE TABLE GDX_CC_DEVICE (
 DEVICE_ID BIGINT NOT NULL,
 MANUFACTURER VARCHAR(80) NOT NULL,
 MODEL_NAME VARCHAR(80) NOT NULL,
 SERIAL_NUMBER VARCHAR(100),
 DEVICE_TYPE VARCHAR(20) NOT NULL,
 FIRMWARE_VERSION VARCHAR(40),
 MEDICAL_CLASS VARCHAR(30),
 ECG_CHANNELS SMALLINT,
 ECG_RESOLUTION_BITS SMALLINT,
 ACTIVE_FLAG SMALLINT DEFAULT 1 NOT NULL,
 CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT PK_GDX_CC_DEVICE PRIMARY KEY (DEVICE_ID),
 CONSTRAINT UQ_GDX_CC_DEV_SERIAL UNIQUE (SERIAL_NUMBER),
 CONSTRAINT CK_GDX_CC_DEV_TYPE CHECK
  (DEVICE_TYPE IN ('ECG','CHEST_STRAP','OPTICAL','SMARTWATCH','OTHER')),
 CONSTRAINT CK_GDX_CC_DEV_ACTIVE CHECK (ACTIVE_FLAG IN (0,1))
);

CREATE TABLE GDX_CC_SESSION (
 SESSION_ID BIGINT NOT NULL,
 ID_PERSON BIGINT NOT NULL,
 DEVICE_ID BIGINT NOT NULL,
 STARTED_AT TIMESTAMP NOT NULL,
 ENDED_AT TIMESTAMP,
 SIGNAL_TYPE VARCHAR(10) NOT NULL,
 ECG_SAMPLE_RATE_HZ INTEGER,
 RR_RESOLUTION_MS SMALLINT,
 MOTION_RATE_HZ NUMERIC(6,1),
 ACC_RANGE_G SMALLINT,
 GYRO_RANGE_DPS SMALLINT,
 TIMEZONE_OFFSET_MIN SMALLINT,
 PROTOCOL_NAME VARCHAR(100),
 BODY_POSITION VARCHAR(20),
 ALGORITHM_NAME VARCHAR(100),
 ALGORITHM_VERSION VARCHAR(40),
 NOTES VARCHAR(1000),
 CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT PK_GDX_CC_SESSION PRIMARY KEY (SESSION_ID),
 CONSTRAINT FK_GDX_CC_SESS_PART FOREIGN KEY (ID_PERSON)
  REFERENCES GDX_CC_PERSON (ID_PERSON),
 CONSTRAINT FK_GDX_CC_SESS_DEV FOREIGN KEY (DEVICE_ID)
  REFERENCES GDX_CC_DEVICE (DEVICE_ID),
 CONSTRAINT CK_GDX_CC_SESS_SIGNAL CHECK (SIGNAL_TYPE IN ('ECG','PPG')),
 CONSTRAINT CK_GDX_CC_SESS_ECG_RATE CHECK
  (ECG_SAMPLE_RATE_HZ IS NULL OR
   ECG_SAMPLE_RATE_HZ IN (125,128,200,250,256,500,512)),
 CONSTRAINT CK_GDX_CC_SESS_RR_RES CHECK
  (RR_RESOLUTION_MS IS NULL OR RR_RESOLUTION_MS IN (1,8)),
 CONSTRAINT CK_GDX_CC_SESS_MOV_RATE CHECK
  (MOTION_RATE_HZ IS NULL OR MOTION_RATE_HZ IN (12.5,26,52,104,208)),
 CONSTRAINT CK_GDX_CC_SESS_ACC CHECK
  (ACC_RANGE_G IS NULL OR ACC_RANGE_G IN (2,4,8,16)),
 CONSTRAINT CK_GDX_CC_SESS_GYRO CHECK
  (GYRO_RANGE_DPS IS NULL OR GYRO_RANGE_DPS IN (125,245,500,1000,2000)),
 CONSTRAINT CK_GDX_CC_SESS_POSITION CHECK
  (BODY_POSITION IS NULL OR BODY_POSITION IN
   ('SUPINE','SITTING','STANDING','MOVING','OTHER')),
 CONSTRAINT CK_GDX_CC_SESS_DATES CHECK
  (ENDED_AT IS NULL OR ENDED_AT >= STARTED_AT)
);

CREATE TABLE GDX_CC_RR_INTERVAL (
 RR_INTERVAL_ID BIGINT NOT NULL,
 SESSION_ID BIGINT NOT NULL,
 BEAT_NUMBER BIGINT NOT NULL,
 MEASURED_AT TIMESTAMP,
 DEVICE_TIME_US BIGINT,
 RR_INTERVAL_MS NUMERIC(10,3) NOT NULL,
 HEART_RATE_BPM NUMERIC(8,3),
 NORMAL_BEAT_FLAG SMALLINT DEFAULT 1 NOT NULL,
 QUALITY_FLAG VARCHAR(15) DEFAULT 'VALID' NOT NULL,
 CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT PK_GDX_CC_RR_INTERVAL PRIMARY KEY (RR_INTERVAL_ID),
 CONSTRAINT FK_GDX_CC_RR_SESS FOREIGN KEY (SESSION_ID)
  REFERENCES GDX_CC_SESSION (SESSION_ID) ON DELETE CASCADE,
 CONSTRAINT UQ_GDX_CC_RR_BEAT UNIQUE (SESSION_ID,BEAT_NUMBER),
 CONSTRAINT CK_GDX_CC_RR_VALUE CHECK (RR_INTERVAL_MS BETWEEN 250 AND 3000),
 CONSTRAINT CK_GDX_CC_RR_HR CHECK
  (HEART_RATE_BPM IS NULL OR HEART_RATE_BPM BETWEEN 20 AND 240),
 CONSTRAINT CK_GDX_CC_RR_NORMAL CHECK (NORMAL_BEAT_FLAG IN (0,1)),
 CONSTRAINT CK_GDX_CC_RR_QUALITY CHECK
  (QUALITY_FLAG IN ('VALID','SUSPECT','ARTIFACT','EXCLUDED'))
);

CREATE TABLE GDX_CC_ECG_SAMPLE (
 ECG_SAMPLE_ID BIGINT NOT NULL,
 SESSION_ID BIGINT NOT NULL,
 SAMPLE_NUMBER BIGINT NOT NULL,
 MEASURED_AT TIMESTAMP,
 DEVICE_TIME_US BIGINT,
 ECG_VALUE_UV NUMERIC(12,3),
 ADC_VALUE SMALLINT,
 QUALITY_FLAG VARCHAR(15) DEFAULT 'VALID' NOT NULL,
 CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT PK_GDX_CC_ECG_SAMPLE PRIMARY KEY (ECG_SAMPLE_ID),
 CONSTRAINT FK_GDX_CC_ECG_SESS FOREIGN KEY (SESSION_ID)
  REFERENCES GDX_CC_SESSION (SESSION_ID) ON DELETE CASCADE,
 CONSTRAINT UQ_GDX_CC_ECG_SAMPLE UNIQUE (SESSION_ID,SAMPLE_NUMBER),
 CONSTRAINT CK_GDX_CC_ECG_QUALITY CHECK
  (QUALITY_FLAG IN ('VALID','SUSPECT','ARTIFACT','EXCLUDED'))
);

CREATE TABLE GDX_CC_MOTION (
 MOTION_ID BIGINT NOT NULL,
 SESSION_ID BIGINT NOT NULL,
 SAMPLE_NUMBER BIGINT NOT NULL,
 MEASURED_AT TIMESTAMP,
 DEVICE_TIME_US BIGINT,
 ACC_X_MS2 NUMERIC(12,6),
 ACC_Y_MS2 NUMERIC(12,6),
 ACC_Z_MS2 NUMERIC(12,6),
 GYRO_X_DPS NUMERIC(12,5),
 GYRO_Y_DPS NUMERIC(12,5),
 GYRO_Z_DPS NUMERIC(12,5),
 MAG_X_MGAUSS NUMERIC(12,5),
 MAG_Y_MGAUSS NUMERIC(12,5),
 MAG_Z_MGAUSS NUMERIC(12,5),
 DEVICE_TEMP_C NUMERIC(6,2),
 CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT PK_GDX_CC_MOTION PRIMARY KEY (MOTION_ID),
 CONSTRAINT FK_GDX_CC_MOTION_SESS FOREIGN KEY (SESSION_ID)
  REFERENCES GDX_CC_SESSION (SESSION_ID) ON DELETE CASCADE,
 CONSTRAINT UQ_GDX_CC_MOTION_SAMPLE UNIQUE (SESSION_ID,SAMPLE_NUMBER),
 CONSTRAINT CK_GDX_CC_MOTION_TEMP CHECK
  (DEVICE_TEMP_C IS NULL OR DEVICE_TEMP_C BETWEEN 0 AND 65)
);

CREATE TABLE GDX_CC_HRV_WINDOW (
 HRV_WINDOW_ID BIGINT NOT NULL,
 SESSION_ID BIGINT NOT NULL,
 WINDOW_STARTED_AT TIMESTAMP NOT NULL,
 WINDOW_ENDED_AT TIMESTAMP NOT NULL,
 WINDOW_SECONDS INTEGER NOT NULL,
 VALID_BEAT_COUNT INTEGER,
 MEAN_RR_MS NUMERIC(10,3),
 MEAN_HEART_RATE_BPM NUMERIC(8,3),
 RMSSD_MS NUMERIC(10,3),
 SDNN_MS NUMERIC(10,3),
 RESPIRATORY_RATE NUMERIC(7,3),
 COHERENCE_INDEX NUMERIC(12,5),
 ARTIFACT_PERCENTAGE NUMERIC(6,3),
 PROTOCOL_PHASE VARCHAR(20) NOT NULL,
 STRESS_CLASS VARCHAR(20),
 CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT PK_GDX_CC_HRV_WINDOW PRIMARY KEY (HRV_WINDOW_ID),
 CONSTRAINT FK_GDX_CC_HRV_SESS FOREIGN KEY (SESSION_ID)
  REFERENCES GDX_CC_SESSION (SESSION_ID) ON DELETE CASCADE,
 CONSTRAINT CK_GDX_CC_HRV_DATES CHECK (WINDOW_ENDED_AT > WINDOW_STARTED_AT),
 CONSTRAINT CK_GDX_CC_HRV_SECONDS CHECK (WINDOW_SECONDS > 0),
 CONSTRAINT CK_GDX_CC_HRV_RMSSD CHECK (RMSSD_MS IS NULL OR RMSSD_MS >= 0),
 CONSTRAINT CK_GDX_CC_HRV_SDNN CHECK (SDNN_MS IS NULL OR SDNN_MS >= 0),
 CONSTRAINT CK_GDX_CC_HRV_ART CHECK
  (ARTIFACT_PERCENTAGE IS NULL OR ARTIFACT_PERCENTAGE BETWEEN 0 AND 100),
 CONSTRAINT CK_GDX_CC_HRV_PHASE CHECK
  (PROTOCOL_PHASE IN ('BASELINE','STIMULUS','INTERACTION','RECOVERY','OTHER')),
 CONSTRAINT CK_GDX_CC_HRV_STRESS CHECK
  (STRESS_CLASS IS NULL OR STRESS_CLASS IN
   ('RELAXED','BASELINE','ACTIVATED','STRESSED','INCONCLUSIVE'))
);

CREATE TABLE GDX_CC_DEVICE_EVENT (
 DEVICE_EVENT_ID BIGINT NOT NULL,
 SESSION_ID BIGINT NOT NULL,
 EVENT_AT TIMESTAMP NOT NULL,
 DEVICE_TIME_US BIGINT,
 EVENT_TYPE VARCHAR(25) NOT NULL,
 SEVERITY_LEVEL VARCHAR(10) DEFAULT 'INFO' NOT NULL,
 BATTERY_PERCENTAGE NUMERIC(5,2),
 EVENT_CODE VARCHAR(50),
 EVENT_DESCRIPTION VARCHAR(500),
 CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 CONSTRAINT PK_GDX_CC_DEVICE_EVENT PRIMARY KEY (DEVICE_EVENT_ID),
 CONSTRAINT FK_GDX_CC_EVENT_SESS FOREIGN KEY (SESSION_ID)
  REFERENCES GDX_CC_SESSION (SESSION_ID) ON DELETE CASCADE,
 CONSTRAINT CK_GDX_CC_EVENT_TYPE CHECK
  (EVENT_TYPE IN ('BATTERY','CONTACT_LOSS','BLUETOOTH','ECG_RESET',
   'DATA_GAP','CLOCK_SYNC','START','STOP','OTHER')),
 CONSTRAINT CK_GDX_CC_EVENT_SEV CHECK
  (SEVERITY_LEVEL IN ('INFO','WARNING','ERROR')),
 CONSTRAINT CK_GDX_CC_EVENT_BAT CHECK
  (BATTERY_PERCENTAGE IS NULL OR BATTERY_PERCENTAGE BETWEEN 0 AND 100)
);

