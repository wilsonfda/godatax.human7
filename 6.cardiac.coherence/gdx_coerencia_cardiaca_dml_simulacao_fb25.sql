/* RR por batimento: 60 intervalos por sessao. */
SET TERM ^ ;
EXECUTE BLOCK AS
 DECLARE VARIABLE S INTEGER;
 DECLARE VARIABLE B INTEGER;
 DECLARE VARIABLE SID INTEGER;
 DECLARE VARIABLE RR NUMERIC(10,3);
 DECLARE VARIABLE T0 TIMESTAMP;
BEGIN
 S = 1;
 WHILE (S <= 5) DO
 BEGIN
  SID = 1000 + S;
  T0 = CASE S
   WHEN 1 THEN CAST('2026-09-10 09:00:00' AS TIMESTAMP)
   WHEN 2 THEN CAST('2026-09-10 09:10:00' AS TIMESTAMP)
   WHEN 3 THEN CAST('2026-09-10 09:20:00' AS TIMESTAMP)
   WHEN 4 THEN CAST('2026-09-10 09:30:00' AS TIMESTAMP)
   ELSE CAST('2026-09-10 09:40:00' AS TIMESTAMP)
  END;
  B = 1;
  WHILE (B <= 60) DO
  BEGIN
   RR = CASE S
    WHEN 1 THEN 850 + MOD(B,6) * 6
    WHEN 2 THEN 642 + MOD(B,5) * 3
    WHEN 3 THEN CASE MOD(B,6)
     WHEN 0 THEN 900 WHEN 1 THEN 960 WHEN 2 THEN 1040
     WHEN 3 THEN 1080 WHEN 4 THEN 1010 ELSE 930 END
    WHEN 4 THEN 780 + MOD(B,7) * 9
    ELSE 760 + MOD(B,4) * 7
   END;
   INSERT INTO GDX_CC_RR_INTERVAL
    (RR_INTERVAL_ID,SESSION_ID,BEAT_NUMBER,MEASURED_AT,DEVICE_TIME_US,
     RR_INTERVAL_MS,HEART_RATE_BPM,NORMAL_BEAT_FLAG,QUALITY_FLAG)
   VALUES
    (SID * 1000 + B,SID,B,DATEADD(SECOND,B,T0),B * 1000000,
     :RR,60000.000 / :RR,1,'VALID');
   B = B + 1;
  END
  S = S + 1;
 END
END^
SET TERM ; ^

