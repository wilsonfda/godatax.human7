/* CONSULTA DE VALIDACAO: recalcula RMSSD diretamente dos intervalos RR. */
SELECT
 C.SESSION_ID,
 COUNT(*) AS DIFFERENCE_COUNT,
 CAST(SQRT(AVG(
  (C.RR_INTERVAL_MS - P.RR_INTERVAL_MS) *
  (C.RR_INTERVAL_MS - P.RR_INTERVAL_MS)
 )) AS NUMERIC(10,3)) AS RMSSD_CALCULATED_MS
FROM GDX_CC_RR_INTERVAL C
JOIN GDX_CC_RR_INTERVAL P
 ON P.SESSION_ID = C.SESSION_ID
AND P.BEAT_NUMBER = C.BEAT_NUMBER - 1
WHERE C.NORMAL_BEAT_FLAG = 1
  AND P.NORMAL_BEAT_FLAG = 1
GROUP BY C.SESSION_ID
ORDER BY C.SESSION_ID;

