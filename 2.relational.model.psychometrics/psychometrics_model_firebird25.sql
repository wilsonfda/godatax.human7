/* Initial psychometrics relational model - Firebird 2.5 */

CREATE TABLE GDX_PSY_PERSON (
  ID_PERSON BIGINT NOT NULL,
  NAME VARCHAR(150) NOT NULL,
  EXTERNAL_IDENTIFIER VARCHAR(60),
  BIRTH_DATE DATE,
  GENDER VARCHAR(30),
  EDUCATION_LEVEL VARCHAR(80),
  REGISTRATION_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_GDX_PSY_PERSON PRIMARY KEY (ID_PERSON),
  CONSTRAINT UQ_GDX_PSY_PERSON_EXT UNIQUE (EXTERNAL_IDENTIFIER)
);

CREATE TABLE GDX_PSY_TEAM (
  ID_TEAM BIGINT NOT NULL,
  NAME VARCHAR(120) NOT NULL,
  DESCRIPTION VARCHAR(500),
  ID_LEADER BIGINT,
  CONSTRAINT PK_GDX_PSY_TEAM PRIMARY KEY (ID_TEAM),
  CONSTRAINT FK_GDX_PSY_TEAM_LEADER FOREIGN KEY (ID_LEADER) REFERENCES GDX_PSY_PERSON(ID_PERSON)
);

CREATE TABLE GDX_PSY_TEAM_MEMBER (
  ID_TEAM BIGINT NOT NULL,
  ID_PERSON BIGINT NOT NULL,
  ROLE VARCHAR(60),
  START_DATE DATE,
  END_DATE DATE,
  CONSTRAINT PK_GDX_PSY_TEAM_MEMBER PRIMARY KEY (ID_TEAM, ID_PERSON),
  CONSTRAINT FK_GDX_PSY_TM_TEAM FOREIGN KEY (ID_TEAM) REFERENCES GDX_PSY_TEAM(ID_TEAM),
  CONSTRAINT FK_GDX_PSY_TM_PERSON FOREIGN KEY (ID_PERSON) REFERENCES GDX_PSY_PERSON(ID_PERSON)
);

CREATE TABLE GDX_PSY_OCCUPATION (
  ID_OCCUPATION BIGINT NOT NULL,
  NAME VARCHAR(120) NOT NULL,
  DESCRIPTION VARCHAR(500),
  CONSTRAINT PK_GDX_PSY_OCCUPATION PRIMARY KEY (ID_OCCUPATION),
  CONSTRAINT UQ_GDX_PSY_OCCUPATION_NAME UNIQUE (NAME)
);

CREATE TABLE GDX_PSY_PERSON_OCCUPATION (
  ID_PERSON BIGINT NOT NULL,
  ID_OCCUPATION BIGINT NOT NULL,
  START_DATE DATE,
  END_DATE DATE,
  CONSTRAINT PK_GDX_PSY_PERSON_OCCUP PRIMARY KEY (ID_PERSON, ID_OCCUPATION, START_DATE),
  CONSTRAINT FK_GDX_PSY_PO_PERSON FOREIGN KEY (ID_PERSON) REFERENCES GDX_PSY_PERSON(ID_PERSON),
  CONSTRAINT FK_GDX_PSY_PO_OCCUPATION FOREIGN KEY (ID_OCCUPATION) REFERENCES GDX_PSY_OCCUPATION(ID_OCCUPATION)
);

CREATE TABLE GDX_PSY_STUDY (
  ID_STUDY BIGINT NOT NULL,
  TITLE VARCHAR(200) NOT NULL,
  OBJECTIVE VARCHAR(1000),
  METHOD VARCHAR(1000),
  START_DATE DATE,
  END_DATE DATE,
  STATUS VARCHAR(30) DEFAULT 'PLANNED' NOT NULL,
  CONSTRAINT PK_GDX_PSY_STUDY PRIMARY KEY (ID_STUDY)
);

CREATE TABLE GDX_PSY_STUDY_PARTICIPANT (
  ID_STUDY BIGINT NOT NULL,
  ID_PERSON BIGINT NOT NULL,
  ANONYMOUS_CODE VARCHAR(60),
  EXPERIMENTAL_GROUP VARCHAR(80),
  ENTRY_DATE DATE,
  CONSENT SMALLINT DEFAULT 0 NOT NULL,
  CONSTRAINT PK_GDX_PSY_STUDY_PARTICIPANT PRIMARY KEY (ID_STUDY, ID_PERSON),
  CONSTRAINT FK_GDX_PSY_SP_STUDY FOREIGN KEY (ID_STUDY) REFERENCES GDX_PSY_STUDY(ID_STUDY),
  CONSTRAINT FK_GDX_PSY_SP_PERSON FOREIGN KEY (ID_PERSON) REFERENCES GDX_PSY_PERSON(ID_PERSON),
  CONSTRAINT CK_GDX_PSY_SP_CONSENT CHECK (CONSENT IN (0,1)),
  CONSTRAINT UQ_GDX_PSY_SP_ANON UNIQUE (ID_STUDY, ANONYMOUS_CODE)
);

CREATE TABLE GDX_PSY_PHENOMENON (
  ID_PHENOMENON BIGINT NOT NULL,
  NAME VARCHAR(120) NOT NULL,
  DESCRIPTION VARCHAR(1000),
  CONSTRAINT PK_GDX_PSY_PHENOMENON PRIMARY KEY (ID_PHENOMENON),
  CONSTRAINT UQ_GDX_PSY_PHENOMENON_NAME UNIQUE (NAME)
);

CREATE TABLE GDX_PSY_CONSTRUCT (
  ID_CONSTRUCT BIGINT NOT NULL,
  ID_PARENT_CONSTRUCT BIGINT,
  NAME VARCHAR(120) NOT NULL,
  DOMAIN VARCHAR(60),
  DEFINITION VARCHAR(1000) NOT NULL,
  CONSTRAINT PK_GDX_PSY_CONSTRUCT PRIMARY KEY (ID_CONSTRUCT),
  CONSTRAINT FK_GDX_PSY_CONSTRUCT_PARENT FOREIGN KEY (ID_PARENT_CONSTRUCT) REFERENCES GDX_PSY_CONSTRUCT(ID_CONSTRUCT),
  CONSTRAINT UQ_GDX_PSY_CONSTRUCT_NAME UNIQUE (NAME)
);

CREATE TABLE GDX_PSY_VARIABLE (
  ID_VARIABLE BIGINT NOT NULL,
  ID_CONSTRUCT BIGINT NOT NULL,
  NAME VARCHAR(150) NOT NULL,
  DESCRIPTION VARCHAR(1000),
  OPERATIONAL_DEFINITION VARCHAR(1000),
  VARIABLE_TYPE VARCHAR(40) DEFAULT 'PSYCHOLOGICAL' NOT NULL,
  MEASUREMENT_LEVEL VARCHAR(30),
  CONSTRAINT PK_GDX_PSY_VARIABLE PRIMARY KEY (ID_VARIABLE),
  CONSTRAINT FK_GDX_PSY_VARIABLE_CONSTRUCT FOREIGN KEY (ID_CONSTRUCT) REFERENCES GDX_PSY_CONSTRUCT(ID_CONSTRUCT),
  CONSTRAINT UQ_GDX_PSY_VARIABLE_NAME UNIQUE (ID_CONSTRUCT, NAME)
);

CREATE TABLE GDX_PSY_INDICATOR (
  ID_INDICATOR BIGINT NOT NULL,
  ID_VARIABLE BIGINT NOT NULL,
  NAME VARCHAR(150) NOT NULL,
  DESCRIPTION VARCHAR(1000),
  OPERATIONAL_DEFINITION VARCHAR(1000),
  INDICATOR_TYPE VARCHAR(30),
  MEASUREMENT_UNIT VARCHAR(40),
  DIRECTION VARCHAR(15),
  MIN_VALUE NUMERIC(14,4),
  MAX_VALUE NUMERIC(14,4),
  CONSTRAINT PK_GDX_PSY_INDICATOR PRIMARY KEY (ID_INDICATOR),
  CONSTRAINT FK_GDX_PSY_INDICATOR_VARIABLE FOREIGN KEY (ID_VARIABLE) REFERENCES GDX_PSY_VARIABLE(ID_VARIABLE),
  CONSTRAINT UQ_GDX_PSY_INDICATOR_NAME UNIQUE (ID_VARIABLE, NAME),
  CONSTRAINT CK_GDX_PSY_INDICATOR_RANGE CHECK (
    MIN_VALUE IS NULL OR MAX_VALUE IS NULL OR MIN_VALUE <= MAX_VALUE
  )
);

CREATE TABLE GDX_PSY_PHENOMENON_CONSTRUCT (
  ID_PHENOMENON BIGINT NOT NULL,
  ID_CONSTRUCT BIGINT NOT NULL,
  RELATION_TYPE VARCHAR(60),
  CONSTRAINT PK_GDX_PSY_PHEN_CONSTRUCT PRIMARY KEY (ID_PHENOMENON, ID_CONSTRUCT),
  CONSTRAINT FK_GDX_PSY_PC_PHENOMENON FOREIGN KEY (ID_PHENOMENON) REFERENCES GDX_PSY_PHENOMENON(ID_PHENOMENON),
  CONSTRAINT FK_GDX_PSY_PC_CONSTRUCT FOREIGN KEY (ID_CONSTRUCT) REFERENCES GDX_PSY_CONSTRUCT(ID_CONSTRUCT)
);

CREATE TABLE GDX_PSY_INSTRUMENT (
  ID_INSTRUMENT BIGINT NOT NULL,
  NAME VARCHAR(160) NOT NULL,
  VERSION VARCHAR(30),
  TYPE VARCHAR(50) NOT NULL,
  DESCRIPTION VARCHAR(1000),
  INSTRUCTIONS BLOB SUB_TYPE TEXT,
  ACTIVE SMALLINT DEFAULT 1 NOT NULL,
  CONSTRAINT PK_GDX_PSY_INSTRUMENT PRIMARY KEY (ID_INSTRUMENT),
  CONSTRAINT CK_GDX_PSY_INSTRUMENT_ACTIVE CHECK (ACTIVE IN (0,1)),
  CONSTRAINT UQ_GDX_PSY_INSTRUMENT UNIQUE (NAME, VERSION)
);

CREATE TABLE GDX_PSY_INSTRUMENT_CONSTRUCT (
  ID_INSTRUMENT BIGINT NOT NULL,
  ID_CONSTRUCT BIGINT NOT NULL,
  WEIGHT NUMERIC(9,4) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_GDX_PSY_INSTRUMENT_CONSTRUCT PRIMARY KEY (ID_INSTRUMENT, ID_CONSTRUCT),
  CONSTRAINT FK_GDX_PSY_IC_INSTRUMENT FOREIGN KEY (ID_INSTRUMENT) REFERENCES GDX_PSY_INSTRUMENT(ID_INSTRUMENT),
  CONSTRAINT FK_GDX_PSY_IC_CONSTRUCT FOREIGN KEY (ID_CONSTRUCT) REFERENCES GDX_PSY_CONSTRUCT(ID_CONSTRUCT)
);

CREATE TABLE GDX_PSY_INSTRUMENT_ITEM (
  ID_ITEM BIGINT NOT NULL,
  ID_INSTRUMENT BIGINT NOT NULL,
  ITEM_ORDER INTEGER NOT NULL,
  STATEMENT_TEXT BLOB SUB_TYPE TEXT NOT NULL,
  RESPONSE_TYPE VARCHAR(30) NOT NULL,
  REQUIRED SMALLINT DEFAULT 1 NOT NULL,
  WEIGHT NUMERIC(9,4) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_GDX_PSY_ITEM PRIMARY KEY (ID_ITEM),
  CONSTRAINT FK_GDX_PSY_ITEM_INSTRUMENT FOREIGN KEY (ID_INSTRUMENT) REFERENCES GDX_PSY_INSTRUMENT(ID_INSTRUMENT),
  CONSTRAINT CK_GDX_PSY_ITEM_REQUIRED CHECK (REQUIRED IN (0,1)),
  CONSTRAINT UQ_GDX_PSY_ITEM_ORDER UNIQUE (ID_INSTRUMENT, ITEM_ORDER)
);

CREATE TABLE GDX_PSY_INDICATOR_ITEM (
  ID_INDICATOR BIGINT NOT NULL,
  ID_ITEM BIGINT NOT NULL,
  WEIGHT NUMERIC(9,4) DEFAULT 1 NOT NULL,
  REVERSED SMALLINT DEFAULT 0 NOT NULL,
  CONSTRAINT PK_GDX_PSY_INDICATOR_ITEM PRIMARY KEY (ID_INDICATOR, ID_ITEM),
  CONSTRAINT FK_GDX_PSY_II_INDICATOR FOREIGN KEY (ID_INDICATOR) REFERENCES GDX_PSY_INDICATOR(ID_INDICATOR),
  CONSTRAINT FK_GDX_PSY_II_ITEM FOREIGN KEY (ID_ITEM) REFERENCES GDX_PSY_INSTRUMENT_ITEM(ID_ITEM),
  CONSTRAINT CK_GDX_PSY_II_REVERSED CHECK (REVERSED IN (0,1))
);

CREATE TABLE GDX_PSY_ITEM_ALTERNATIVE (
  ID_ALTERNATIVE BIGINT NOT NULL,
  ID_ITEM BIGINT NOT NULL,
  ALTERNATIVE_ORDER INTEGER NOT NULL,
  LABEL VARCHAR(300) NOT NULL,
  NUMERIC_VALUE NUMERIC(12,4),
  CONSTRAINT PK_GDX_PSY_ALTERNATIVE PRIMARY KEY (ID_ALTERNATIVE),
  CONSTRAINT FK_GDX_PSY_ALTERNATIVE_ITEM FOREIGN KEY (ID_ITEM) REFERENCES GDX_PSY_INSTRUMENT_ITEM(ID_ITEM),
  CONSTRAINT UQ_GDX_PSY_ALTERNATIVE_ORDER UNIQUE (ID_ITEM, ALTERNATIVE_ORDER)
);

CREATE TABLE GDX_PSY_EVALUATOR (
  ID_EVALUATOR BIGINT NOT NULL,
  ID_PERSON BIGINT NOT NULL,
  PROFESSIONAL_LICENSE VARCHAR(60),
  SPECIALTY VARCHAR(100),
  CONSTRAINT PK_GDX_PSY_EVALUATOR PRIMARY KEY (ID_EVALUATOR),
  CONSTRAINT FK_GDX_PSY_EVALUATOR_PERSON FOREIGN KEY (ID_PERSON) REFERENCES GDX_PSY_PERSON(ID_PERSON),
  CONSTRAINT UQ_GDX_PSY_EVALUATOR_PERSON UNIQUE (ID_PERSON)
);

CREATE TABLE GDX_PSY_APPLICATION (
  ID_APPLICATION BIGINT NOT NULL,
  ID_STUDY BIGINT NOT NULL,
  ID_PERSON BIGINT NOT NULL,
  ID_INSTRUMENT BIGINT NOT NULL,
  ID_EVALUATOR BIGINT,
  START_TIMESTAMP TIMESTAMP,
  END_TIMESTAMP TIMESTAMP,
  CONTEXT VARCHAR(500),
  STATUS VARCHAR(30) DEFAULT 'STARTED' NOT NULL,
  CONSTRAINT PK_GDX_PSY_APPLICATION PRIMARY KEY (ID_APPLICATION),
  CONSTRAINT FK_GDX_PSY_APP_PARTICIPANT FOREIGN KEY (ID_STUDY, ID_PERSON)
    REFERENCES GDX_PSY_STUDY_PARTICIPANT(ID_STUDY, ID_PERSON),
  CONSTRAINT FK_GDX_PSY_APP_INSTRUMENT FOREIGN KEY (ID_INSTRUMENT) REFERENCES GDX_PSY_INSTRUMENT(ID_INSTRUMENT),
  CONSTRAINT FK_GDX_PSY_APP_EVALUATOR FOREIGN KEY (ID_EVALUATOR) REFERENCES GDX_PSY_EVALUATOR(ID_EVALUATOR)
);

CREATE TABLE GDX_PSY_ITEM_RESPONSE (
  ID_RESPONSE BIGINT NOT NULL,
  ID_APPLICATION BIGINT NOT NULL,
  ID_ITEM BIGINT NOT NULL,
  ID_ALTERNATIVE BIGINT,
  NUMERIC_VALUE NUMERIC(12,4),
  TEXT_VALUE BLOB SUB_TYPE TEXT,
  RESPONDED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_GDX_PSY_RESPONSE PRIMARY KEY (ID_RESPONSE),
  CONSTRAINT FK_GDX_PSY_RESPONSE_APPLICATION FOREIGN KEY (ID_APPLICATION) REFERENCES GDX_PSY_APPLICATION(ID_APPLICATION),
  CONSTRAINT FK_GDX_PSY_RESPONSE_ITEM FOREIGN KEY (ID_ITEM) REFERENCES GDX_PSY_INSTRUMENT_ITEM(ID_ITEM),
  CONSTRAINT FK_GDX_PSY_RESPONSE_ALTERNATIVE FOREIGN KEY (ID_ALTERNATIVE) REFERENCES GDX_PSY_ITEM_ALTERNATIVE(ID_ALTERNATIVE),
  CONSTRAINT UQ_GDX_PSY_RESPONSE UNIQUE (ID_APPLICATION, ID_ITEM)
);

CREATE TABLE GDX_PSY_CONSTRUCT_RESULT (
